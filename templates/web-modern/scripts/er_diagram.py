#!/usr/bin/env python3
"""
Write an ER diagram of SQLAlchemy models as Mermaid (renders on GitHub and in most Markdown viewers).
No Graphviz or native build step needed.

  python scripts/er_diagram.py app.models:Base docs/database-er.md

The first argument is "module:attribute" pointing at a declarative Base or a MetaData object.
Run it from the directory where that module can be imported, after every schema change.
"""

from __future__ import annotations

import importlib
import sys
from pathlib import Path


def load_metadata(target: str):
    module_name, _, attr = target.partition(":")
    obj = getattr(importlib.import_module(module_name), attr or "Base")
    return getattr(obj, "metadata", obj)


def mermaid_type(column) -> str:
    try:
        name = str(column.type)
    except Exception:  # some dialect-specific types cannot render without a dialect
        name = type(column.type).__name__
    return name.split("(")[0].replace(" ", "_") or "UNKNOWN"


def render(metadata) -> str:
    lines = ["```mermaid", "erDiagram"]
    for table in sorted(metadata.sorted_tables, key=lambda t: t.name):
        lines.append(f"    {table.name} {{")
        for column in table.columns:
            keys = [k for k, on in (("PK", column.primary_key), ("FK", column.foreign_keys), ("UK", column.unique)) if on]
            note = ' "nullable"' if column.nullable and not column.primary_key else ""
            lines.append(f"        {mermaid_type(column)} {column.name}{' ' + ','.join(keys) if keys else ''}{note}")
        lines.append("    }")
    for table in sorted(metadata.sorted_tables, key=lambda t: t.name):
        for fk in sorted(table.foreign_keys, key=lambda f: f.parent.name):
            parent = fk.column.table.name
            # Parent side: exactly one when the FK is required, zero or one when nullable. Child side: zero or more
            one = "|o" if fk.parent.nullable else "||"
            lines.append(f"    {parent} {one}--o{{ {table.name} : {fk.parent.name}")
    lines.append("```")
    return "\n".join(lines) + "\n"


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    sys.path.insert(0, str(Path.cwd()))
    out = Path(sys.argv[2])
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(f"# Database ER diagram\n\nGenerated by `scripts/er_diagram.py`; do not edit by hand.\n\n{render(load_metadata(sys.argv[1]))}", encoding="utf-8")
    print(f"Wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
